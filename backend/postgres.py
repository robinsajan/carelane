"""PostgreSQL connection adapter for the application's small SQL interface.

Keep the SQLite test/offline backend while adapting the known application SQL
to PostgreSQL. Values remain bound parameters; identifiers are never user input.
"""
import re
import threading

import psycopg
from psycopg_pool import ConnectionPool

_pools = {}
_lock = threading.Lock()
_applications = 0
IDENTITY_TABLES = {
    'settings', 'users', 'departments', 'doctors', 'lookups', 'patients',
    'history', 'visits', 'token_allocations', 'visit_events', 'billing_charges',
    'bills', 'bill_payments', 'followups', 'followup_events', 'contacts', 'audits',
}


class Row(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class Result:
    def __init__(self, cursor=None, lastrowid=None, rows=None):
        self.cursor, self.lastrowid, self.rows = cursor, lastrowid, rows

    def _row(self, values):
        return None if values is None else Row(zip((c.name for c in self.cursor.description), values))

    def fetchone(self):
        if self.rows is not None:
            return self.rows.pop(0) if self.rows else None
        return self._row(self.cursor.fetchone())

    def fetchall(self):
        if self.rows is not None:
            rows, self.rows = self.rows, []
            return rows
        return [self._row(row) for row in self.cursor.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


def translate(sql):
    """Translate only the SQL dialect differences used by this application."""
    sql = sql.strip().rstrip(';')
    ignore = bool(re.match(r'INSERT OR IGNORE\b', sql, re.I))
    sql = re.sub(r'INSERT OR IGNORE\b', 'INSERT', sql, flags=re.I)
    sql = re.sub(r'([\w.]+)\s+COLLATE NOCASE', r'LOWER(\1)', sql, flags=re.I)
    sql = re.sub(r'\bLIKE\b', 'ILIKE', sql, flags=re.I)
    sql = sql.replace('max(value,?)', 'GREATEST(value,?)')
    # PostgreSQL <16 requires aliases for derived tables. Also works on newer versions.
    if sql.startswith('SELECT count(*) FROM ('):
        sql += ' AS counted_rows'
    if ignore:
        sql += ' ON CONFLICT DO NOTHING'
    insert = re.match(r'INSERT INTO\s+(\w+)\b', sql, re.I)
    returning = bool(insert and insert.group(1).lower() in IDENTITY_TABLES)
    if returning:
        sql += ' RETURNING id'
    return sql.replace('%', '%%').replace('?', '%s'), returning


class Connection:
    dialect = 'postgresql'

    def __init__(self, pool, schema='public'):
        if not re.fullmatch(r'[a-z_][a-z0-9_]*', schema):
            raise ValueError('Invalid PostgreSQL schema identifier.')
        self.pool, self.schema = pool, schema
        self.raw = pool.getconn()
        self.closed = False
        self.settings_cache = None

    def execute(self, sql, parameters=()):
        if sql in ('BEGIN', 'BEGIN IMMEDIATE'):
            with self.raw.pipeline():
                self.raw.execute('BEGIN')
                if sql == 'BEGIN':
                    # Multi-query reads (bill + payment history, counts + rows)
                    # must observe one committed snapshot, as SQLite did.
                    self.raw.execute('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ')
                self.raw.execute(f'SET LOCAL search_path TO "{self.schema}"')
                self.raw.execute("SET LOCAL statement_timeout = '20s'")
                if sql == 'BEGIN IMMEDIATE':
                    # Preserve version-check and idempotency read-before-write guarantees.
                    self.raw.execute('SELECT pg_advisory_xact_lock(732019861)')
            return Result(rows=[])
        if self.raw.info.transaction_status == psycopg.pq.TransactionStatus.IDLE:
            self.execute('BEGIN')
        if re.match(r'UPDATE\s+settings\b', sql, re.I):
            self.settings_cache = None
        sql, returning = translate(sql)
        values = tuple(int(v) if isinstance(v, bool) else v for v in parameters)
        cursor = self.raw.execute(sql, values or None)
        if returning:
            row = cursor.fetchone()
            return Result(rows=[], lastrowid=row[0] if row else None)
        return Result(cursor)

    def executescript(self, script):
        self.execute('BEGIN IMMEDIATE')
        statements = []
        for statement in script.split(';'):
            statement = statement.strip()
            if not statement:
                continue
            statement = statement.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
            statement = re.sub(r'\bid INTEGER PRIMARY KEY\b', 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', statement)
            statement = statement.replace(' COLLATE NOCASE', '')
            # Known DDL and seed SQL are translated once, then sent in one pipeline.
            statements.append(translate(statement)[0])
        for table, columns in {'users': ['username'], 'departments': ['name', 'code'],
                               'doctors': ['code'], 'billing_charges': ['name']}.items():
            for column in columns:
                statements.append(f'CREATE UNIQUE INDEX IF NOT EXISTS {table}_{column}_casefold ON {table}(LOWER({column}))')
        with self.raw.pipeline():
            for statement in statements:
                self.raw.execute(statement)

    def executemany(self, sql, values):
        statement, _ = translate(sql)
        self.raw.cursor().executemany(statement, values)

    def columns(self, table):
        return {row['column_name'] for row in self.execute(
            'SELECT column_name FROM information_schema.columns WHERE table_schema=? AND table_name=?', (self.schema, table))}

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        if not self.closed:
            self.closed = True
            self.pool.putconn(self.raw)

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        try:
            self.rollback() if kind else self.commit()
        finally:
            self.close()


def connect(url, schema='public'):
    with _lock:
        if url not in _pools:
            pool = ConnectionPool(url, min_size=0, max_size=8, timeout=20,
                                  kwargs={'prepare_threshold': None, 'connect_timeout': 10}, open=False)
            pool.open()
            _pools[url] = pool
        pool = _pools[url]
    return Connection(pool, schema)


def close_pools():
    with _lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


def acquire_application():
    global _applications
    with _lock:
        _applications += 1


def release_application():
    global _applications
    with _lock:
        _applications -= 1
        if _applications == 0:
            for pool in _pools.values():
                pool.close()
            _pools.clear()
